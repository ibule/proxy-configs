#!/usr/bin/env python3
"""Sync Johnshall/Shadowrocket-ADBlock-Rules-Forever ad rules into a Shadowrocket rule set.

Source: sr_ad_only.conf (rebuilt daily at 08:00 Asia/Shanghai by upstream).
Output: shadowrocket/ADBlock.list, referenced by shadowrocket/ADBlock.module with REJECT.

Only DOMAIN-SUFFIX / DOMAIN / IP-CIDR / IP-CIDR6 rules are kept; the policy field is
stripped so the module decides the policy. IP rules get no-resolve.
Python 3 standard library only.
"""
from __future__ import annotations

import argparse
import ipaddress
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_URL = "https://johnshall.github.io/Shadowrocket-ADBlock-Rules-Forever/sr_ad_only.conf"
OUTPUT = ROOT / "shadowrocket" / "ADBlock.list"
EXCLUDE_FILE = ROOT / "rules" / "adblock_exclude.txt"

MIN_RULES = 10000
MAX_RULES = 200000
MAX_DELETE_RATIO = 0.25

DOMAIN_RE = re.compile(r"^(?=.{1,253}$)(?!-)[a-z0-9_-]+(\.[a-z0-9_-]+)*$")
DOMAIN_TYPES = {"DOMAIN-SUFFIX", "DOMAIN"}
IP_TYPES = {"IP-CIDR", "IP-CIDR6"}


class SyncError(Exception):
    pass


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "proxy-configs-adblock-sync"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        if getattr(resp, "status", 200) not in (200, None):
            raise SyncError(f"HTTP {resp.status} for {url}")
        return resp.read().decode("utf-8")


def load_excludes(path: Path = EXCLUDE_FILE) -> set[str]:
    if not path.exists():
        return set()
    out = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip().lower().lstrip(".")
        if line:
            out.add(line)
    return out


def is_excluded(domain: str, excludes: set[str]) -> bool:
    parts = domain.split(".")
    for i in range(len(parts)):
        if ".".join(parts[i:]) in excludes:
            return True
    return False


def parse_rules(text: str, excludes: set[str] | None = None) -> list[str]:
    excludes = excludes or set()
    in_rule = False
    seen: set[str] = set()
    rules: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", "//", ";")):
            continue
        if line.startswith("[") and line.endswith("]"):
            in_rule = line.lower() == "[rule]"
            continue
        if not in_rule:
            continue
        fields = [f.strip() for f in line.split(",")]
        if len(fields) < 2:
            continue
        kind = fields[0].upper()
        value = fields[1]
        if kind in DOMAIN_TYPES:
            value = value.lower().rstrip(".")
            if not DOMAIN_RE.match(value) or "." not in value:
                continue
            if is_excluded(value, excludes):
                continue
            rule = f"{kind},{value}"
        elif kind in IP_TYPES:
            try:
                net = ipaddress.ip_network(value, strict=False)
            except ValueError:
                continue
            kind = "IP-CIDR6" if net.version == 6 else "IP-CIDR"
            rule = f"{kind},{net.with_prefixlen},no-resolve"
        else:
            continue
        if rule not in seen:
            seen.add(rule)
            rules.append(rule)
    return rules


def render(rules: list[str]) -> str:
    domains = sorted(r for r in rules if not r.startswith("IP-"))
    ips = sorted(r for r in rules if r.startswith("IP-"))
    header = [
        "# NAME: ADBlock",
        "# SOURCE: https://github.com/Johnshall/Shadowrocket-ADBlock-Rules-Forever (sr_ad_only.conf)",
        "# GENERATED BY: scripts/sync_adblock_rules.py (policy field stripped; module sets REJECT)",
        f"# TOTAL: {len(rules)}",
    ]
    return "\n".join(header + domains + ips) + "\n"


def existing_rules(path: Path = OUTPUT) -> list[str]:
    if not path.exists():
        return []
    return [l for l in path.read_text(encoding="utf-8").splitlines() if l and not l.startswith("#")]


def validate(new: list[str], old: list[str]) -> None:
    if len(new) < MIN_RULES:
        raise SyncError(f"too few rules: {len(new)} < {MIN_RULES}")
    if len(new) > MAX_RULES:
        raise SyncError(f"too many rules: {len(new)} > {MAX_RULES}")
    if old:
        removed = len(set(old) - set(new))
        if removed / len(old) > MAX_DELETE_RATIO:
            raise SyncError(f"would delete {removed}/{len(old)} rules (> {MAX_DELETE_RATIO:.0%})")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if output would change")
    ap.add_argument("--source", default=SOURCE_URL)
    args = ap.parse_args(argv)
    try:
        rules = parse_rules(fetch(args.source), load_excludes())
        validate(rules, existing_rules())
    except (SyncError, OSError, UnicodeDecodeError) as e:
        print(f"sync failed: {e}", file=sys.stderr)
        return 2
    content = render(rules)
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if content == current:
        print("No changes.")
        return 0
    if args.check:
        print("Output would change.")
        return 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(rules)} rules).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
